#!/usr/bin/env python3
"""Writes scripts/itemc/itemc_sens.yaml and params.json (the final method + one threshold changed per variant).
Edit the lists below and re-run to change what is tried: python3 scripts/itemc/make_config.py"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
base = {"DSLAM_KF_SWITCH": 1, "DSLAM_KF_MIN_GAP": 10, "DSLAM_KF_SWITCH_MIN": 0.05, "DSLAM_KF_SWITCH_HOLD": 30,
        "DSLAM_KF_SWITCH_GEO": 0.3, "DSLAM_KF_SWITCH_GEO_Z": 3.09, "DSLAM_KF_SWITCH_GEO_KEEP": 150,
        "DSLAM_KF_SWITCH_GEO_MINCONF": 2,
        "DSLAM_MAP_FILTER": 2, "DSLAM_MAP_FILTER_DEPTH": 0.5, "DSLAM_MAP_FILTER_SITES": 3, "DSLAM_MAP_FILTER_INIT": -1}
params = [
    ("DSLAM_KF_SWITCH_MIN",         "YMIN",  "share of keypoints in YOLO boxes for a hit",            [0.02, 0.10]),
    ("DSLAM_KF_SWITCH_GEO",         "GEO",   "min outlier ratio inside the box",                      [0.2, 0.25, 0.4, 0.5]),
    ("DSLAM_KF_SWITCH_GEO_Z",       "Z",     "z-test level (1.64 p<.05, 2.33 .01, 3.72 1e-4, 4.26 1e-5)", [1.64, 2.33, 3.72, 4.26]),
    ("DSLAM_KF_SWITCH_GEO_MINCONF", "CONF",  "confirmations before the long hold",                    [1, 3]),
    ("DSLAM_KF_SWITCH_HOLD",        "HOLD",  "short hold [frames]",                                   [15, 60]),
    ("DSLAM_KF_SWITCH_GEO_KEEP",    "KEEP",  "long hold [frames]",                                    [75, 300]),
    ("DSLAM_KF_MIN_GAP",            "GAP",   "keyframe cap: min frames between keyframes",            [5, 8, 15, 20]),
    ("DSLAM_MAP_FILTER_DEPTH",      "BAND",  "map filter depth band [m]",                             [0.25, 0.75, 1.0]),
]
seqs = ["freiburg3_walking_xyz", "freiburg3_walking_rpy", "freiburg3_sitting_xyz", "freiburg3_sitting_halfsphere",
        "freiburg1_room", "bonn_crowd3"]
fmt = lambda d: "{" + ", ".join(f"{k}: {v}" for k, v in d.items()) + "}"
n_var = 1 + sum(len(p[3]) for p in params)
L = ["# Item C: sensitivity of the final method (GEOK2Z_MF) to each of its 8 thresholds, one at a time.",
     "# Each variant changes ONE value; everything else stays at the final setting (variant DEFAULT).",
     "# Development sequences only (TUM + the unused Bonn crowd3); the Bonn test set is not touched.",
     f"# Generated by scripts/itemc/make_config.py. {n_var} variants, {len(seqs)} sequences, 3 runs = "
     f"{n_var * len(seqs) * 3} runs (~8 h).",
     "#   python3 scripts/eval/run_experiments.py scripts/itemc/itemc_sens.yaml --dry-run",
     "#   python3 scripts/eval/run_experiments.py scripts/itemc/itemc_sens.yaml",
     "#   python3 scripts/eval/evaluate.py        scripts/itemc/itemc_sens.yaml",
     "#   python3 scripts/itemc/sensitivity.py    scripts/itemc/itemc_sens.yaml",
     "# Parameters (default in brackets):"]
for k, n, m, vals in params:
    L.append(f"#   {n:5s} {k:28s} {m} [{base[k]}]; tried {vals}")
L += ["name: itemc_sens", "runs: 3", "orbslam_root: ~/ORB_SLAM3", "data_root: ~/datasets", "results_root: results",
      "fail_threshold_m: 0.1", "bonn_gt: bonn_tm", "", "common_env:",
      "  DSLAM_MODE: baseline", "  DSLAM_CHI2_GATE: raw", "  DSLAM_LABELS: opt", "  DSLAM_KERNEL: huber",
      "  DSLAM_IGNORE: \"\"", "  DSLAM_KF_SEMANTIC: 0", "  DSLAM_DIAG: 0", "  DSLAM_KF_CAP_BYPASS: 0", "",
      "baseline: DEFAULT", "variants:", f"  DEFAULT: {fmt(base)}"]
for k, n, m, vals in params:
    for v in vals:
        d = dict(base)
        d[k] = v
        L.append(f"  {n}_{v}: {fmt(d)}")
L += ["", "sequences:"] + [f"  - {s}" for s in seqs]
open(os.path.join(HERE, "itemc_sens.yaml"), "w").write("\n".join(L) + "\n")
json.dump([{"env": k, "name": n, "meaning": m, "default": base[k], "values": vals} for k, n, m, vals in params],
          open(os.path.join(HERE, "params.json"), "w"), indent=1)
print(f"wrote itemc_sens.yaml ({n_var} variants) and params.json")
